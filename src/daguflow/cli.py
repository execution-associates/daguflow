"""`daguflow build | validate | run | schema`."""

from __future__ import annotations

import argparse
import difflib
import importlib
import importlib.util
import pkgutil
import re
import sys
from pathlib import Path
from types import ModuleType

import yaml


from . import schema
from .compile import GENERATED_MARKER
from .dag import DAG, collect


def _import_target(target: str) -> list[ModuleType]:
    """A dotted module, a .py file, or a package directory, plus its submodules."""
    path = Path(target)
    if path.suffix == ".py" and path.is_file():
        parent = str(path.resolve().parent)
        if parent not in sys.path:
            sys.path.insert(0, parent)
        return [importlib.import_module(path.stem)]
    if path.is_dir() and (path / "__init__.py").is_file():
        parent = str(path.resolve().parent)
        if parent not in sys.path:
            sys.path.insert(0, parent)
        target = path.resolve().name
    elif str(Path.cwd()) not in sys.path:
        sys.path.insert(0, str(Path.cwd()))
    module = importlib.import_module(target)
    modules = [module]
    if hasattr(module, "__path__"):
        for info in pkgutil.walk_packages(module.__path__, prefix=module.__name__ + "."):
            modules.append(importlib.import_module(info.name))
    return modules


def discover(targets: list[str]) -> list[DAG]:
    found: dict[int, DAG] = {}
    for target in targets:
        for module in _import_target(target):
            for d in collect(module):
                found.setdefault(id(d), d)
    dags = sorted(found.values(), key=lambda d: d.name)
    names = [d.name for d in dags]
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        raise SystemExit(f"two DAGs share a name: {', '.join(dupes)}")
    return dags


def _is_generated(path: Path) -> bool:
    try:
        with path.open() as f:
            return f.readline().startswith(GENERATED_MARKER)
    except OSError:
        return False


def cmd_build(args: argparse.Namespace) -> int:
    out = Path(args.out)
    root = Path(args.root) if args.root else Path.cwd()
    dags = discover(args.targets)
    if not dags:
        print("no DAGs found", file=sys.stderr)
        return 1
    rendered = {f"{d.name}.yaml": d.to_yaml(root=root) for d in dags}
    stale_files = sorted(p for p in out.glob("*.yaml") if p.name not in rendered and _is_generated(p)) \
        if out.is_dir() else []
    if args.check:
        bad = 0
        for filename, text in rendered.items():
            path = out / filename
            current = path.read_text() if path.exists() else ""
            if current != text:
                bad += 1
                sys.stdout.writelines(difflib.unified_diff(
                    current.splitlines(keepends=True), text.splitlines(keepends=True),
                    fromfile=str(path), tofile=f"{path} (from Python)"))
        for path in stale_files:
            bad += 1
            print(f"{path}: generated by daguflow but no DAG produces it any more")
        if bad:
            print(f"\n{bad} file(s) out of date: run daguflow build", file=sys.stderr)
            return 1
        print(f"{len(rendered)} DAG file(s) up to date")
        return 0
    out.mkdir(parents=True, exist_ok=True)
    for filename, text in rendered.items():
        path = out / filename
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"wrote {path}")
    if args.prune:
        for path in stale_files:
            path.unlink()
            print(f"removed {path}")
    elif stale_files:
        print("stale (use --prune): " + ", ".join(p.name for p in stale_files), file=sys.stderr)
    return 0


def cmd_validate(args: argparse.Namespace) -> int:
    from .validate import ValidationError, check_documents, with_binary

    failed = 0
    client = None
    if args.server:
        from .client import Client

        client = Client(args.server, token=args.token)
    for name in args.files:
        path = Path(name)
        text = path.read_text()
        problems: list[str] = []
        try:
            check_documents([d for d in yaml.safe_load_all(text) if d is not None], label=str(path))
        except ValidationError as e:
            problems.append(str(e))
        if args.dagu_bin:
            problems.extend(with_binary(path, args.dagu_bin))
        if client is not None:
            result = client.validate(text, name=path.stem)
            if not result.get("valid"):
                problems.extend(f"server: {e}" for e in result.get("errors") or ["invalid"])
        if problems:
            failed += 1
            print(f"FAIL {path}\n  " + "\n  ".join(problems))
        else:
            print(f"ok   {path}")
    return 1 if failed else 0


def _kv(pairs: list[str]) -> dict[str, str]:
    out = {}
    for pair in pairs:
        key, sep, value = pair.partition("=")
        if not sep:
            raise SystemExit(f"-p takes key=value, not {pair!r}")
        out[key] = value
    return out


def cmd_run(args: argparse.Namespace) -> int:
    from .client import Client

    params = _kv(args.param)
    with Client(args.server, token=args.token) as client:
        if args.inline:
            dags = {d.name: d for d in discover([args.inline])}
            if args.dag not in dags:
                raise SystemExit(f"{args.dag} is not defined in {args.inline}")
            run_id = client.run_inline(dags[args.dag].to_yaml(), name=args.dag, params=params or None)
        else:
            run_id = client.start(args.dag, params=params or None)
        print(run_id)
        if not args.wait:
            return 0
        run = client.wait(args.dag, run_id, timeout=args.timeout)
        print(run.status_label)
        for key, value in client.outputs(args.dag, run_id).items():
            print(f"{key}: {value}")
        return 0 if run.succeeded else 1


def cmd_schema(args: argparse.Namespace) -> int:
    if args.action == "show":
        cached = schema.cache_path()
        print(f"dagu {schema.DAGU_VERSION} ({schema.DAGU_COMMIT}), sha256 {schema.DAGU_SCHEMA_SHA256}")
        print(f"cache: {cached} ({'present' if cached.exists() else 'not fetched yet'})")
        return 0
    if args.action == "fetch":
        print(schema.fetch(Path(args.out) if args.out else None))
        return 0
    import hashlib

    import httpx

    init = Path(args.repo).resolve() / "src" / "daguflow" / "schema" / "__init__.py"
    if not init.is_file():
        raise SystemExit(f"{args.repo} is not a daguflow checkout (no src/daguflow/schema/__init__.py)")
    version = args.version if args.version.startswith("v") else "v" + args.version
    commit = httpx.get(f"https://api.github.com/repos/dagucloud/dagu/commits/{version}",
                       timeout=60).raise_for_status().json()["sha"]
    url = f"https://raw.githubusercontent.com/dagucloud/dagu/{commit}/internal/cmn/schema/dag.schema.json"
    digest = hashlib.sha256(httpx.get(url, timeout=60).raise_for_status().content).hexdigest()
    text = init.read_text()
    for name, value in (("DAGU_VERSION", version), ("DAGU_COMMIT", commit), ("DAGU_SCHEMA_SHA256", digest)):
        text = re.sub(rf'{name} = "[^"]*"', f'{name} = "{value}"', text)
    init.write_text(text)
    print(f"schema -> {version} ({commit[:12]}); now run: python tools/gen_actions.py > src/daguflow/actions/_generated.py")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="daguflow", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    b = sub.add_parser("build", help="write one YAML file per DAG")
    b.add_argument("targets", nargs="+", help="module, package directory or .py file")
    b.add_argument("-o", "--out", required=True, help="output directory")
    b.add_argument("--check", action="store_true", help="write nothing; exit 1 if any file is stale")
    b.add_argument("--prune", action="store_true", help="delete generated files no DAG produces")
    b.add_argument("--root", help="paths in header comments are relative to this (default: cwd)")
    b.set_defaults(fn=cmd_build)

    v = sub.add_parser("validate", help="check YAML files")
    v.add_argument("files", nargs="+")
    v.add_argument("--dagu-bin", help="also run `dagu validate` with this binary")
    v.add_argument("--server", help="also POST each file to this dagu's /dags/validate")
    v.add_argument("--token")
    v.set_defaults(fn=cmd_validate)

    r = sub.add_parser("run", help="start a DAG run")
    r.add_argument("dag")
    r.add_argument("--server", required=True)
    r.add_argument("--token")
    r.add_argument("-p", "--param", action="append", default=[], help="key=value (repeatable)")
    r.add_argument("--inline", metavar="MODULE", help="send this module's DAG as an inline spec")
    r.add_argument("--wait", action="store_true")
    r.add_argument("--timeout", type=float, default=300)
    r.set_defaults(fn=cmd_run)

    s = sub.add_parser("schema", help="show, fetch or (in a daguflow checkout) repin dagu's schema")
    s.add_argument("action", choices=["show", "fetch", "update"])
    s.add_argument("--out", help="where fetch writes it (default: the cache build reads)")
    s.add_argument("--version", help="dagu release tag, e.g. v2.24.0 (update)")
    s.add_argument("--repo", default=".", help="daguflow checkout (update)")
    s.set_defaults(fn=cmd_schema)

    args = parser.parse_args(argv)
    if args.command == "schema" and args.action == "update" and not args.version:
        parser.error("schema update needs --version")
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
