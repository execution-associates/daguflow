"""DAG -> YAML text, deterministically, so a stale file is a visible diff."""

from __future__ import annotations

import os
from pathlib import Path
from typing import TYPE_CHECKING, Any

import yaml

from . import schema

if TYPE_CHECKING:
    from .dag import DAG

GENERATED_MARKER = "# Generated by daguflow"


class _Dumper(yaml.SafeDumper):
    """Block style everywhere, `|` for multi-line strings, keys in given order."""

    def increase_indent(self, flow: bool = False, indentless: bool = False) -> Any:
        # Indent list items under their key, as hand-written dagu YAML does.
        return super().increase_indent(flow, False)


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    if "\n" in value:
        # A trailing space on any line forces PyYAML out of block style;
        # strip it rather than emit an unreadable quoted string.
        value = "\n".join(line.rstrip() for line in value.split("\n"))
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", value)


_Dumper.add_representer(str, _str)


def dump(document: dict[str, Any]) -> str:
    return yaml.dump(document, Dumper=_Dumper, sort_keys=False, default_flow_style=False,
                     allow_unicode=True, width=1 << 16)


def _relative(path: str | None, root: Path | None) -> str | None:
    if not path:
        return None
    try:
        return os.path.relpath(path, root or Path.cwd())
    except ValueError:
        return path


def header(dag: DAG, root: Path | None = None) -> str:
    source = _relative(dag.source, root)
    where = f" from {source}" if source else ""
    lines = [f"{GENERATED_MARKER}{where} (dagu {schema.DAGU_VERSION}). Edit the Python, not this file."]
    if dag.doc:
        lines.append("#")
        lines.extend(("# " + line).rstrip() for line in dag.doc.splitlines())
    return "\n".join(lines) + "\n"


def to_yaml(dag: DAG, *, root: Path | None = None, validate: bool = True) -> str:
    documents = dag.documents()
    if validate:
        from .validate import check_documents

        check_documents(documents, label=f"{dag.name}.yaml")
    return header(dag, root) + "---\n".join(dump(d) for d in documents)
