from datetime import timedelta

import pytest

from daguflow import DAG, Cron, Ref, Step, chain, dag, on_exit, on_failure, shell, step


def test_docstring_splits_into_description_and_header():
    @dag(labels=["a"])
    def d():
        """One line summary

        Longer story
        on two lines."""
        shell("true", name="s")

    assert d.description == "One line summary"
    text = d.to_yaml()
    assert "# Longer story\n# on two lines." in text
    assert text.splitlines()[0].startswith("# Generated by daguflow")


def test_entrypoint_has_no_name_and_keys_are_ordered():
    with DAG("d", description="x", labels=["l"], schedule=Cron("0 1 * * *", tz="UTC"),
             env={"A": "1"}, timeout=timedelta(minutes=5), params={"p": 1}) as d:
        shell("echo", name="s")
    body = d.to_dict()
    assert "name" not in body
    assert list(body) == ["description", "labels", "schedule", "params", "env", "timeout_sec", "steps"]
    assert body["schedule"] == "CRON_TZ=UTC 0 1 * * *"
    assert body["env"] == [{"A": "1"}]
    assert body["timeout_sec"] == 300


def test_tags_become_labels():
    with DAG("d", tags=["x"]) as d:
        shell("echo", name="s")
    assert d.to_dict()["labels"] == ["x"]


def test_unknown_keys_fail_at_build_time():
    with pytest.raises(TypeError, match="unknown dagu DAG key"):
        DAG("d", timout_sec=3)
    with DAG("d2"):
        with pytest.raises(TypeError, match="unknown dagu step key"):
            Step("s", run="x", retry_polcy={})


def test_invalid_names():
    with pytest.raises(ValueError):
        DAG("has space")
    with DAG("d"):
        with pytest.raises(ValueError):
            Step("s", run="x", id="has-hyphen")


def test_rshift_lists_and_chain():
    with DAG("d") as d:
        a, b, c, e = (shell("true", name=n) for n in "abce")
        a >> [b, c] >> e
    steps = {s["name"]: s for s in d.to_dict()["steps"]}
    assert steps["b"]["depends"] == "a" and steps["c"]["depends"] == "a"
    assert steps["e"]["depends"] == ["b", "c"]

    with DAG("d2") as d2:
        x, y, z = (shell("true", name=n) for n in "xyz")
        chain(x, [y], z)
        z << Step("w", run="true")
    names = {s["name"]: s.get("depends") for s in d2.to_dict()["steps"]}
    assert names["y"] == "x" and names["z"] == ["y", "w"]


def test_reading_an_output_adds_the_dependency():
    with DAG("d") as d:
        fetch = shell("curl x", name="fetch")
        shell(f"echo {fetch.output['id']}", name="use")          # Ref object
        shell("echo ${FETCH}", name="text")                       # written as text
        shell("echo $FETCH", name="bare")
        shell("echo ${fetch.stdout}", name="by-step")
        shell("echo ${OTHER}", name="unrelated")
    deps = {s["name"]: s.get("depends") for s in d.to_dict()["steps"]}
    assert deps == {"fetch": None, "use": "fetch", "text": "fetch", "bare": "fetch",
                    "by-step": "fetch", "unrelated": None}


def test_auto_depends_can_be_turned_off():
    with DAG("d", auto_depends=False) as d:
        shell("x", name="a", output="A")
        shell("echo ${A}", name="b")
    assert "depends" not in d.to_dict()["steps"][1]


def test_cycles_and_unknown_depends_are_errors():
    with DAG("d") as d:
        a = shell("true", name="a")
        b = shell("true", name="b")
        a >> b >> a
    with pytest.raises(ValueError, match="cycle"):
        d.to_dict()
    with DAG("d2") as d2:
        shell("true", name="a", depends="nope")
    with pytest.raises(ValueError, match="unknown step"):
        d2.to_dict()


def test_duplicate_step_names():
    with DAG("d") as d:
        shell("true", name="a")
        shell("true", name="a")
    with pytest.raises(ValueError, match="repeat"):
        d.to_dict()


def test_handlers():
    with DAG("d") as d:
        shell("true", name="main")
        with on_failure():
            shell("notify", name="alert")
        with on_exit():
            step("cleanup", run="rm -f x")
    body = d.to_dict()
    assert [s["name"] for s in body["steps"]] == ["main"]
    assert body["handler_on"] == {"failure": {"name": "alert", "run": "notify"},
                                  "exit": {"name": "cleanup", "run": "rm -f x"}}


def test_retries_carry_an_interval():
    with DAG("d") as d:
        shell("true", name="a", retries=3)
        shell("true", name="b", retries=1, retry_interval=timedelta(seconds=30))
        shell("true", name="c", retry_policy={"limit": 2, "interval_sec": 9, "backoff": True})
    steps = d.to_dict()["steps"]
    assert steps[0]["retry_policy"] == {"limit": 3, "interval_sec": 5}
    assert steps[1]["retry_policy"] == {"limit": 1, "interval_sec": 30}
    assert steps[2]["retry_policy"] == {"limit": 2, "interval_sec": 9, "backoff": True}


def test_with_dag_registers_and_params_namespace():
    from daguflow.dag import registered

    with DAG("reg", params={"who": "x"}) as d:
        shell(f"echo {d.params.who}", name="s")
    assert d in registered()
    assert d.to_dict()["steps"][0]["run"] == "echo ${who}"


def test_step_format_means_its_output():
    with DAG("d") as d:
        a = shell("echo 1", name="a")
        shell(f"echo {a} {a:q}", name="b")
    assert d.to_dict()["steps"][1]["run"] == 'echo ${A} "${A}"'


def test_refs_in_with_blocks_render():
    from daguflow import actions

    with DAG("d") as d:
        src = shell("echo /tmp/x", name="src")
        actions.file.read(path=src.output).step("read")
    read = d.to_dict()["steps"][1]
    assert read["with"]["path"] == "${SRC}" and read["depends"] == "src"
    assert isinstance(src.output, Ref)
