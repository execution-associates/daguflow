import shutil
from pathlib import Path

import pytest
import yaml

from daguflow import DAG, shell
from daguflow.cli import main
from daguflow.compile import dump
from daguflow.validate import ValidationError

REPO = Path(__file__).resolve().parents[1]
GOLDEN = REPO / "tests" / "golden"


def test_examples_match_golden_files(tmp_path):
    assert main(["build", str(REPO / "examples"), "-o", str(tmp_path), "--root", str(REPO)]) == 0
    built = sorted(p.name for p in tmp_path.glob("*.yaml"))
    assert built == sorted(p.name for p in GOLDEN.glob("*.yaml"))
    for name in built:
        assert (tmp_path / name).read_text() == (GOLDEN / name).read_text(), name


def test_check_reports_stale_and_orphaned_files(tmp_path, capsys):
    shutil.copytree(GOLDEN, tmp_path / "dags")
    out = tmp_path / "dags"
    assert main(["build", str(REPO / "examples"), "-o", str(out), "--root", str(REPO), "--check"]) == 0
    (out / "hello.yaml").write_text((out / "hello.yaml").read_text() + "# drift\n")
    (out / "gone.yaml").write_text("# Generated by daguflow from old.py\nsteps: []\n")
    (out / "handwritten.yaml").write_text("steps:\n  - name: a\n    run: x\n")
    assert main(["build", str(REPO / "examples"), "-o", str(out), "--root", str(REPO), "--check"]) == 1
    text = capsys.readouterr().out
    assert "hello.yaml" in text and "gone.yaml" in text and "handwritten" not in text
    assert main(["build", str(REPO / "examples"), "-o", str(out), "--root", str(REPO), "--prune"]) == 0
    assert not (out / "gone.yaml").exists() and (out / "handwritten.yaml").exists()
    assert (out / "hello.yaml").read_text() == (GOLDEN / "hello.yaml").read_text()


def test_multiline_strings_are_block_scalars():
    text = dump({"run": "set -eu\necho a  \necho b\n"})
    assert text == "run: |\n  set -eu\n  echo a\n  echo b\n"
    assert yaml.safe_load(text)["run"] == "set -eu\necho a\necho b\n"


def test_build_validates_against_the_schema():
    with DAG("bad") as d:
        shell("echo", name="s", continue_on="sometimes")
    with pytest.raises(ValidationError, match="continue_on"):
        d.to_yaml()


def test_output_is_deterministic():
    def make():
        with DAG("same", env={"B": "2", "A": "1"}) as d:
            shell("echo ${A}", name="one", output="ONE")
            shell("echo ${ONE}", name="two")
        return d.to_yaml()

    assert make() == make()
